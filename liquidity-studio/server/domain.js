/**
 * Generates a full 4-format Marketing Campaign Pack (Infographic, Carousel, IG Story, Reel)
 * from a single backlog item using the pluggable AI Gateway.
 */
export async function generateMultiFormatCampaign({ gateway, story, brandProfile = DEFAULT_BRAND_PROFILE }) {
  const claims = getApprovedClaims(story);
  const expectedCampaign = campaignFromApprovedClaims(story);
  const systemInstruction = `You format approved source excerpts for ${brandProfile.brandName}.
Content domain: ${brandProfile.contentDomain || 'general'}. Preserve source meaning and units.
Controlled excerpt mode: return the supplied campaign JSON exactly. Do not add facts, labels, statistics or claims.
All output requires editorial review. Source approval is not proof of scientific or financial truth.`;
  const prompt = `Approved source claims:\n${JSON.stringify(claims.map(({ id, text, sourceUrl, kind }) => ({ id, text, sourceUrl, kind })))}\nReturn this exact campaign JSON:\n${JSON.stringify(expectedCampaign)}`;

  const responseSchema = {
    type: 'OBJECT',
    properties: {
      infographic: {
        type: 'OBJECT',
        properties: {
          headline: { type: 'STRING' },
          statRows: { type: 'ARRAY', items: { type: 'STRING' } },
          bottomTakeaway: { type: 'STRING' },
          caption: { type: 'STRING' }
        },
        required: ['headline', 'statRows', 'bottomTakeaway', 'caption']
      },
      carousel: {
        type: 'OBJECT',
        properties: {
          coverHook: { type: 'STRING' },
          slides: {
            type: 'ARRAY',
            items: {
              type: 'OBJECT',
              properties: {
                slideNumber: { type: 'INTEGER' },
                title: { type: 'STRING' },
                bodyMetric: { type: 'STRING' },
                visualNote: { type: 'STRING' }
              },
              required: ['slideNumber', 'title', 'bodyMetric', 'visualNote']
            }
          }
        },
        required: ['coverHook', 'slides']
      },
      story: {
        type: 'OBJECT',
        properties: {
          hookBanner: { type: 'STRING' },
          keyStatHighlight: { type: 'STRING' },
          interactiveStickerPrompt: { type: 'STRING' }
        },
        required: ['hookBanner', 'keyStatHighlight', 'interactiveStickerPrompt']
      },
      reel: {
        type: 'OBJECT',
        properties: {
          spokenHook0to3s: { type: 'STRING' },
          beats: {
            type: 'ARRAY',
            items: {
              type: 'OBJECT',
              properties: {
                timecode: { type: 'STRING' },
                voiceover: { type: 'STRING' },
                onScreenText: { type: 'STRING' },
                bRollDirection: { type: 'STRING' }
              },
              required: ['timecode', 'voiceover', 'onScreenText', 'bRollDirection']
            }
          },
          closingCta: { type: 'STRING' }
        },
        required: ['spokenHook0to3s', 'beats', 'closingCta']
      }
    },
    required: ['infographic', 'carousel', 'story', 'reel']
  };

  return gateway.generateStructured({
    systemInstruction,
    prompt,
    responseSchema,
    traceMeta: { operation: 'generate_4format_campaign', storyId: story.id, story, brandId: brandProfile.id, contentDomain: brandProfile.contentDomain }
  });
}


